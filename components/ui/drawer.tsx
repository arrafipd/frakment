"use client";

import type * as React from "react";
import { useCallback, useEffect, useRef } from "react";
import { Drawer as DrawerPrimitive } from "vaul";
import { cn } from "@/lib/utils";

const Drawer = ({
  onOpenChange,
  sounds = false,
  ...props
}: React.ComponentProps<typeof DrawerPrimitive.Root> & {
  sounds?: boolean;
}) => {
  const playOpen = useCallback(() => {}, []);
  const playClose = useCallback(() => {}, []);
  const isControlled = props.open !== undefined;
  const lastOpen = useRef(props.open ?? props.defaultOpen ?? false);

  const playStateSound = useCallback(
    (open: boolean) => {
      if (!sounds || open === lastOpen.current) {
        return;
      }

      if (open) {
        playOpen();
      } else {
        playClose();
      }

      lastOpen.current = open;
    },
    [playClose, playOpen, sounds]
  );

  useEffect(() => {
    if (!isControlled) {
      return;
    }

    playStateSound(props.open ?? false);
  }, [isControlled, playStateSound, props.open]);

  const handleOpenChange = useCallback(
    (open: boolean) => {
      playStateSound(open);
      onOpenChange?.(open);
    },
    [onOpenChange, playStateSound]
  );

  if (!sounds) {
    return (
      <DrawerPrimitive.Root
        data-slot="drawer"
        onOpenChange={onOpenChange}
        {...props}
      />
    );
  }

  return (
    <DrawerPrimitive.Root
      data-slot="drawer"
      onOpenChange={handleOpenChange}
      {...props}
    />
  );
};

